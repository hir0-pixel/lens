#!/usr/bin/env node
/**
 * Generate TypeScript and Python representations of the RAG contracts (Track 1).
 *
 * Both representations embed the canonical schema digests so that
 * scripts/contracts/rag-check.mjs can detect drift.
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(import.meta.url), "../../..");
const ragDir = join(root, "contracts/rag");
const registry = JSON.parse(await readFile(join(ragDir, "registry.v1.json"), "utf8"));

const digestOf = async (name) => createHash("sha256").update((await raw(name)).replace(/\r\n/g, "\n")).digest("hex");
const raws = {};
function raw(name) {
  if (!raws[name]) raws[name] = readFile(join(ragDir, name), "utf8");
  return raws[name];
}

const digests = {};
for (const name of Object.values(registry.contracts)) {
  digests[name] = await digestOf(name);
}
const digestLines = Object.entries(digests).sort(([a], [b]) => a.localeCompare(b));
const digestObject = `{\n    ${digestLines.map(([name, digest]) => `"${name}": "${digest}"`).join(",\n    ")},\n  }`;

const tsPath = join(root, "libs/rag-contracts/index.ts");
const pyDir = join(root, "Enterprise-RAG/contracts");
const pyPath = join(pyDir, "rag_contracts.py");

await mkdir(join(root, "libs/rag-contracts"), { recursive: true });
await mkdir(pyDir, { recursive: true });

await writeFile(
  tsPath,
  `/* Generated by scripts/contracts/rag-generate.mjs from contracts/rag/*.v1.schema.json. Do not edit directly. */
export const RAG_CONTRACT_VERSION = "1.0.0" as const;
export const SCHEMA_DIGESTS = ${digestObject};

export type RetrievalStatus = "context" | "no_context" | "denied_policy" | "failed_downstream";
export type RetrievalMode = "lexical" | "semantic" | "graph" | "hybrid" | "structured" | "citation_refresh";
export type ClassificationRef = "public" | "internal" | "confidential" | "restricted";
export type RagErrorCode = "INVALID_ARGUMENT" | "UNAUTHENTICATED" | "FORBIDDEN" | "STALE_AUTHORITY" | "RATE_LIMITED" | "OVERLOADED" | "DEPENDENCY_UNAVAILABLE" | "DEADLINE_EXCEEDED" | "CANCELLED" | "NOT_FOUND_OR_NOT_DISCLOSABLE" | "QUARANTINED";

export interface RagRequest {
  request_id: string;
  turn_id: string;
  subject_ref: string;
  session_ref: string;
  device_ref: string;
  application_id: "lens-employee-client";
  purpose_ref: string;
  retrieval_class: "enterprise-grounded";
  query_digest: \`sha256:\${string}\`;
  deadline_at: number;
  cancellation: boolean;
  retry_budget: number;
  bulkhead: "interactive" | "management";
  capability: string;
}

export interface RetrievalRequest {
  request_id: string;
  turn_id: string;
  caller_workload_ref: "ai-orchestrator";
  subject_ref: string;
  session_ref: string;
  device_ref: string;
  application_id: "lens-employee-client";
  query_digest: \`sha256:\${string}\`;
  query_text: string;
  purpose_ref: string;
  retrieval_class: "enterprise-grounded";
  corpus_ref: string;
  mode: RetrievalMode;
  candidate_limit: number;
  deadline_at: number;
  cancellation: boolean;
  bulkhead: "interactive" | "management";
  visibility_minimum: number;
}

export interface RetrievedSource {
  document_version_ref: string;
  chunk_ref: string;
  content_digest: \`sha256:\${string}\`;
  citation_anchor: string;
  classification_ref: ClassificationRef;
}

export interface RetrievedContext extends RetrievedSource {
  text: string;
}

export interface AuthorizationManifest {
  digest: \`sha256:\${string}\`;
  retrieved_at: number;
  source_revision_digest: \`sha256:\${string}\`;
  operation_decision_ref: string;
  candidate_decision_ref: string;
  policy_revision: number;
  subject_security_revision: number;
  resource_security_revision_digest: \`sha256:\${string}\`;
  expires_at: number;
  sources: readonly RetrievedSource[];
}

export type RetrievalResult =
  | { status: "context"; retrieval_id: string; request_id: string; turn_id: string; visibility_sequence: number; index_generation: string; context_digest: \`sha256:\${string}\`; manifest: AuthorizationManifest; sources: readonly RetrievedContext[] }
  | { status: "no_context" }
  | { status: "denied_policy" }
  | { status: "failed_downstream" };

export interface RagError {
  error: "RAG_REQUEST_FAILED";
  code: RagErrorCode;
  message: string;
  retryable: boolean;
  retry_after_ms?: number;
  correlation_id: string;
}
`,
  "utf8",
);

await writeFile(
  pyPath,
  `# Generated by scripts/contracts/rag-generate.mjs from contracts/rag/*.v1.schema.json. Do not edit directly.
from dataclasses import dataclass, field
from typing import List, Literal, Optional

RAG_CONTRACT_VERSION: str = "1.0.0"
SCHEMA_DIGESTS = ${digestObject}

ClassificationRef = Literal["public", "internal", "confidential", "restricted"]
RetrievalStatus = Literal["context", "no_context", "denied_policy", "failed_downstream"]
RetrievalMode = Literal["lexical", "semantic", "graph", "hybrid", "structured", "citation_refresh"]
RagErrorCode = Literal[
    "INVALID_ARGUMENT", "UNAUTHENTICATED", "FORBIDDEN", "STALE_AUTHORITY",
    "RATE_LIMITED", "OVERLOADED", "DEPENDENCY_UNAVAILABLE", "DEADLINE_EXCEEDED",
    "CANCELLED", "NOT_FOUND_OR_NOT_DISCLOSABLE", "QUARANTINED",
]


@dataclass(frozen=True)
class RetrievedSource:
    document_version_ref: str
    chunk_ref: str
    content_digest: str
    citation_anchor: str
    classification_ref: ClassificationRef


@dataclass(frozen=True)
class RetrievedContext(RetrievedSource):
    text: str


@dataclass(frozen=True)
class AuthorizationManifest:
    digest: str
    retrieved_at: int
    source_revision_digest: str
    operation_decision_ref: str
    candidate_decision_ref: str
    policy_revision: int
    subject_security_revision: int
    resource_security_revision_digest: str
    expires_at: int
    sources: List[RetrievedSource]


@dataclass(frozen=True)
class RetrievalRequest:
    request_id: str
    turn_id: str
    caller_workload_ref: Literal["ai-orchestrator"]
    subject_ref: str
    session_ref: str
    device_ref: str
    application_id: Literal["lens-employee-client"]
    query_digest: str
    query_text: str
    purpose_ref: str
    retrieval_class: Literal["enterprise-grounded"]
    corpus_ref: str
    mode: RetrievalMode
    candidate_limit: int
    deadline_at: int
    cancellation: bool
    bulkhead: Literal["interactive", "management"]
    visibility_minimum: int


@dataclass(frozen=True)
class RetrievalResult:
    status: RetrievalStatus
    retrieval_id: Optional[str] = None
    request_id: Optional[str] = None
    turn_id: Optional[str] = None
    visibility_sequence: Optional[int] = None
    index_generation: Optional[str] = None
    context_digest: Optional[str] = None
    manifest: Optional[AuthorizationManifest] = None
    sources: List[RetrievedContext] = field(default_factory=list)


@dataclass(frozen=True)
class RagError:
    error: Literal["RAG_REQUEST_FAILED"]
    code: RagErrorCode
    message: str
    retryable: bool
    retry_after_ms: Optional[int] = None
    correlation_id: str = ""
`,
  "utf8",
);

console.log(`Generated ${tsPath} and ${pyPath} from contracts/rag@${registry.version}`);
